export function getHubBySlug(slug) {
  return HUBS.find((h) => h.slug === slug) || null;
}

// 記事が属するハブ（なければ null）
export function getHubForPost(post) {
  if (post.hub) return getHubBySlug(post.hub);
  return HUBS.find((h) => h.clusters.includes(post.cluster)) || null;
}

export function hubPath(hub) {
  return `/category/${hub.slug}/`;
}
